log = logging.getLogger("math-engine.services.topology")


def compute_metadata(graph: nx.Graph, planarity_limit: int = 1000) -> GraphMetadata:
    """
    Derive topological invariants from a validated NetworkX graph.
    """
    n: int = graph.number_of_nodes()
    m: int = graph.number_of_edges()

    density: float = nx.density(graph)
    is_connected: bool = nx.is_connected(graph) if n > 0 else False
    num_components: int = nx.number_connected_components(graph) if n > 0 else 0

    if m <= planarity_limit:
        is_planar, _ = nx.check_planarity(graph)
    else:
        is_planar = None
        log.info(
            "Planarity check skipped: |E| = %d > %d limit.",
            m,
            planarity_limit,
        )

    return GraphMetadata(
        num_nodes=n,
        num_edges=m,
        density=round(density, 6),
        is_connected=is_connected,
        num_connected_components=num_components,
        is_planar=is_planar,
    )


def compute_full_topology(graph: nx.Graph) -> TopologyMetadata:
    """
    Compute Combinatorial Laplacian eigenvalues, Normalized Laplacian, Cheeger bounds,
    Heat Kernel Signatures, Betti numbers, triangles, H1 cycle generators, and neural saliency.
    """
    spec = compute_spectral_topology(graph)
    homology = compute_simplicial_homology(graph)
    saliency = compute_gradient_saliency(graph)
    family_classification = classify_graph(graph)

    # Phase 6: Mathematical Frontiers (Ihara Zeta & Ollivier-Ricci Curvature)
    ihara_data = None
    ricci_data = None
    try:
        if graph.number_of_nodes() <= 60:
            ihara_data = compute_ihara_zeta(graph)
    except Exception as e:
        log.warning(f"Ihara zeta calculation skipped: {e}")

    try:
        if graph.number_of_edges() <= 200:
            ricci_data = compute_ollivier_ricci(graph)
    except Exception as e:
        log.warning(f"Ricci curvature calculation skipped: {e}")

    return TopologyMetadata(
        laplacian_eigenvalues=spec["laplacian_eigenvalues"],
        fiedler_vector=spec["fiedler_vector"],
        algebraic_connectivity=spec["algebraic_connectivity"],
        betti_numbers=homology["betti_numbers"],
        saliency_scores=saliency,
        normalized_eigenvalues=spec["normalized_eigenvalues"],
        spectral_gap=spec["spectral_gap"],
        cheeger_bounds=spec["cheeger_bounds"],
        heat_kernel_signatures=spec["heat_kernel_signatures"],
        h1_generators=homology["h1_generators"],
        triangles=homology["triangles"],
        graph_family=family_classification,
        ihara_zeta=ihara_data,
        ricci_curvature=ricci_data,
    )


def generate_python_export(graph: nx.Graph) -> str:
    """
    Generate standalone Python script reproducing the parsed graph state
    and spectral Laplacian analysis.
    """
    nodes_repr = repr(list(graph.nodes()))
    edges_repr = repr(list(graph.edges()))

    return f'''import networkx as nx
import numpy as np
import scipy.linalg as la

# Generated by Visual Mathematical Discovery Engine
G = nx.Graph()
G.add_nodes_from({nodes_repr})
G.add_edges_from({edges_repr})

# Compute Laplacian
L = nx.laplacian_matrix(G).todense()
eigenvalues = la.eigvalsh(L)
print(f"Algebraic Connectivity: {{eigenvalues[1]:.4f}}")
'''
