/** Export 3D vertices and triangular faces to Wavefront OBJ format. */
export function exportToOBJ(
  nodes: { id: string | number; fx?: number; fy?: number; fz?: number }[],
  faces: (string | number)[][],
  filename: string = "mathematical_surface.obj"
) {
  let obj = "# Visual Mathematical Discovery Engine - 3D Surface Export\n";
  obj += `# Generated at: ${new Date().toISOString()}\n`;
  obj += `# Vertices: ${nodes.length}, Faces: ${faces.length}\n\n`;

  const idMap = new Map<string | number, number>();
  nodes.forEach((n, idx) => {
    idMap.set(n.id, idx + 1); // OBJ is 1-indexed
    const x = (n.fx ?? 0).toFixed(5);
    const y = (n.fy ?? 0).toFixed(5);
    const z = (n.fz ?? 0).toFixed(5);
    obj += `v ${x} ${y} ${z}\n`;
  });

  obj += "\n# Triangular Faces\n";
  faces.forEach((f) => {
    const v0 = idMap.get(f[0]);
    const v1 = idMap.get(f[1]);
    const v2 = idMap.get(f[2]);
    if (v0 && v1 && v2) {
      obj += `f ${v0} ${v1} ${v2}\n`;
    }
  });

  triggerDownload(filename, obj, "text/plain");
}

/** Export 3D vertices and triangular faces to standard ASCII STL format for 3D printing. */
export function exportToSTL(
  nodes: { id: string | number; fx?: number; fy?: number; fz?: number }[],
  faces: (string | number)[][],
  filename: string = "mathematical_surface.stl"
) {
  const nodeMap = new Map<string | number, [number, number, number]>();
  nodes.forEach((n) => {
    nodeMap.set(n.id, [n.fx ?? 0, n.fy ?? 0, n.fz ?? 0]);
  });

  let stl = "solid mathematical_variety\n";

  faces.forEach((f) => {
    const p0 = nodeMap.get(f[0]);
    const p1 = nodeMap.get(f[1]);
    const p2 = nodeMap.get(f[2]);
    if (!p0 || !p1 || !p2) return;

    // Normal calculation: (p1 - p0) x (p2 - p0)
    const u = [p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]];
    const v = [p2[0] - p0[0], p2[1] - p0[1], p2[2] - p0[2]];
    let nx = u[1] * v[2] - u[2] * v[1];
    let ny = u[2] * v[0] - u[0] * v[2];
    let nz = u[0] * v[1] - u[1] * v[0];
    const len = Math.sqrt(nx * nx + ny * ny + nz * nz);
    if (len > 1e-8) {
      nx /= len;
      ny /= len;
      nz /= len;
    }

    stl += `  facet normal ${nx.toFixed(5)} ${ny.toFixed(5)} ${nz.toFixed(5)}\n`;
    stl += "    outer loop\n";
    stl += `      vertex ${p0[0].toFixed(5)} ${p0[1].toFixed(5)} ${p0[2].toFixed(5)}\n`;
    stl += `      vertex ${p1[0].toFixed(5)} ${p1[1].toFixed(5)} ${p1[2].toFixed(5)}\n`;
    stl += `      vertex ${p2[0].toFixed(5)} ${p2[1].toFixed(5)} ${p2[2].toFixed(5)}\n`;
    stl += "    endloop\n";
    stl += "  endfacet\n";
  });

  stl += "endsolid mathematical_variety\n";
  triggerDownload(filename, stl, "application/sla");
}

/** Generate publication-ready LaTeX table code. */
export function generateLaTeXTable(
  title: string,
  rows: { name: string; formula: string; value: string | number }[]
): string {
  let tex = `% --- Generated by Visual Mathematical Discovery Engine ---\n`;
  tex += `\\begin{table}[htbp]\n`;
  tex += `  \\centering\n`;
  tex += `  \\caption{Computed Invariants: ${title}}\n`;
  tex += `  \\begin{tabular}{llr}\n`;
  tex += `    \\toprule\n`;
  tex += `    \\textbf{Invariant} & \\textbf{Mathematical Definition} & \\textbf{Value} \\\\\n`;
  tex += `    \\midrule\n`;

  rows.forEach((r) => {
    tex += `    ${r.name} & $${r.formula}$ & \\texttt{${r.value}} \\\\\n`;
  });

  tex += `    \\bottomrule\n`;
  tex += `  \\end{tabular}\n`;
  tex += `  \\label{tab:${title.toLowerCase().replace(/[^a-z0-9]/g, "_")}}\n`;
  tex += `\\end{table}\n`;
  return tex;
}

/** Trigger browser file download. */
function triggerDownload(filename: string, content: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
